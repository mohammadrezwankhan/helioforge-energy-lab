"""Build every eligible frozen Python preset; browser edits never execute this engine."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api"))
from helioforge.hybrid import HybridRequest, applicability, catalog
from helioforge.engines.hybrid import simulate_hybrid

BUNDLE_VERSION = "hybrid-presets-v1"


def digest(value: object) -> str:
    canonical = json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(canonical.encode()).hexdigest()


def build_bundle(c: dict) -> dict:
    cases = []
    for system in c["systems"]:
        for scenario in c["scenarios"]:
            if system["mode"] != "screening" or scenario["mode"] != "screening" or not applicability(system, scenario):
                continue
            request = HybridRequest(**{**system["preset"], "scenario_id": scenario["id"],
                "hours": max(system["preset"]["hours"], scenario["modifiers"].get("hours", 0))})
            inputs = request.model_dump()
            identifier = f"{BUNDLE_VERSION}/{system['id']}/{scenario['id']}"
            result = simulate_hybrid(request)
            result.update(bundle_case_id=identifier, bundle_version=BUNDLE_VERSION, input_sha256=digest(inputs))
            cases.append({"id": identifier, "inputs": inputs, "result": result})
    if len(cases) != 285 or len({case["id"] for case in cases}) != 285:
        raise ValueError("The public catalogue contract requires exactly 285 distinct numerical presets.")
    return {"schema": "helioforge.hybrid-bundle.v1", "version": BUNDLE_VERSION,
            "catalogue_version": c["version"], "dataset_sha256": digest(cases), "cases": cases}


def main() -> None:
    c = catalog()
    bundle = build_bundle(c)
    text = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    source = ("// Generated by scripts/generate-hybrid-assets.py; edit Python models and catalogue instead.\n"
              "namespace HF {\n export const HYBRID_CATALOG:HybridCatalogue = " + text(c)
              + ";\n export const HYBRID_BUNDLE:HybridBundle = " + text(bundle)
              + ";\n export const HYBRID_EXAMPLE:HybridResult = HYBRID_BUNDLE.cases[0]!.result;\n}\n")
    (ROOT / "apps/web/src/hybrid-data.ts").write_text(source, encoding="utf-8")
    (ROOT / "examples/hybrid-default.json").write_text(json.dumps(c["systems"][0]["preset"], indent=2) + "\n")
    (ROOT / "examples/hybrid-catalog.json").write_text(json.dumps(c, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "examples/hybrid-bundle.json").write_text(text(bundle) + "\n", encoding="utf-8")
    matrix = []
    for system in c["systems"]:
        for scenario in c["scenarios"]:
            mode = ("inapplicable" if not applicability(system, scenario) else
                    "runnable" if system["mode"] == scenario["mode"] == "screening" else "study")
            matrix.append({"system_id": system["id"], "scenario_id": scenario["id"], "capability": mode})
    (ROOT / "examples/hybrid-matrix.json").write_text(json.dumps({"catalogue_version": c["version"], "matrix": matrix}, indent=2) + "\n")
    print(json.dumps({"architectures": len(c["systems"]), "scenarios": len(c["scenarios"]),
                      "lessons": len(c["lessons"]), "bundled_cases": len(bundle["cases"]),
                      "dataset_sha256": bundle["dataset_sha256"]}))


if __name__ == "__main__":
    main()
