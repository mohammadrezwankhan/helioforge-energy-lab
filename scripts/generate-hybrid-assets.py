"""Build every eligible frozen Python preset; browser edits never execute this engine."""

import hashlib
import json
import sys
from pathlib import Path
from typing import TypedDict

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps/api"))
from helioforge.engines.hybrid import simulate_hybrid  # noqa: E402 -- Local source package set above.
from helioforge.hybrid import HybridRequest, applicability, catalog  # noqa: E402 -- Local source package.
from helioforge.hybrid_types import HybridCatalog, HybridPreset  # noqa: E402 -- Local source package.

BUNDLE_VERSION = "hybrid-presets-v1"


class BundleCase(TypedDict):
    id: str
    inputs: dict[str, object]
    result: dict[str, object]


class HybridBundle(TypedDict):
    schema: str
    version: str
    catalogue_version: str
    dataset_sha256: str
    cases: list[BundleCase]


def digest(value: object) -> str:
    canonical = json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)
    return hashlib.sha256(canonical.encode()).hexdigest()


def build_bundle(c: HybridCatalog) -> HybridBundle:
    cases: list[BundleCase] = []
    for system in c["systems"]:
        for scenario in c["scenarios"]:
            if (
                system["mode"] != "screening"
                or scenario["mode"] != "screening"
                or not applicability(system, scenario)
            ):
                continue
            configuration: HybridPreset = {
                **system["preset"],
                "scenario_id": scenario["id"],
                "hours": max(system["preset"]["hours"], scenario["modifiers"].get("hours", 0)),
            }
            request = HybridRequest(**configuration)
            inputs = request.model_dump()
            identifier = f"{BUNDLE_VERSION}/{system['id']}/{scenario['id']}"
            result: dict[str, object] = dict(simulate_hybrid(request))
            result.update(
                bundle_case_id=identifier, bundle_version=BUNDLE_VERSION, input_sha256=digest(inputs)
            )
            cases.append({"id": identifier, "inputs": inputs, "result": result})
    if len(cases) != 285 or len({case["id"] for case in cases}) != 285:
        raise ValueError("The public catalogue contract requires exactly 285 distinct numerical presets.")
    return {
        "schema": "helioforge.hybrid-bundle.v1",
        "version": BUNDLE_VERSION,
        "catalogue_version": c["version"],
        "dataset_sha256": digest(cases),
        "cases": cases,
    }


def main() -> None:
    c = catalog()
    bundle = build_bundle(c)

    def text(value: object) -> str:
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False)

    source = (
        "// Generated by scripts/generate-hybrid-assets.py; edit Python models and catalogue instead.\n"
        "namespace HF {\n export const HYBRID_CATALOG:HybridCatalogue = "
        + text(c)
        + ";\n export const HYBRID_BUNDLE:HybridBundle = "
        + text(bundle)
        + ";\n export const HYBRID_EXAMPLE:HybridResult = HYBRID_BUNDLE.cases[0]!.result;\n}\n"
    )
    (ROOT / "apps/web/src/hybrid-data.ts").write_text(source, encoding="utf-8", newline="\n")
    (ROOT / "examples/hybrid-default.json").write_text(
        json.dumps(c["systems"][0]["preset"], indent=2) + "\n", newline="\n"
    )
    (ROOT / "examples/hybrid-catalog.json").write_text(
        json.dumps(c, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n"
    )
    (ROOT / "examples/hybrid-bundle.json").write_text(text(bundle) + "\n", encoding="utf-8", newline="\n")
    matrix = []
    for system in c["systems"]:
        for scenario in c["scenarios"]:
            mode = (
                "inapplicable"
                if not applicability(system, scenario)
                else "runnable"
                if system["mode"] == scenario["mode"] == "screening"
                else "study"
            )
            matrix.append({"system_id": system["id"], "scenario_id": scenario["id"], "capability": mode})
    (ROOT / "examples/hybrid-matrix.json").write_text(
        json.dumps({"catalogue_version": c["version"], "matrix": matrix}, indent=2) + "\n", newline="\n"
    )
    print(  # noqa: T201 -- CLI report output.
        json.dumps(
            {
                "architectures": len(c["systems"]),
                "scenarios": len(c["scenarios"]),
                "lessons": len(c["lessons"]),
                "bundled_cases": len(bundle["cases"]),
                "dataset_sha256": bundle["dataset_sha256"],
            }
        )
    )


if __name__ == "__main__":
    main()
